// Run with PGlite installed locally or point PGLITE_MODULE at a temporary installation.
const {PGlite}=await import(process.env.PGLITE_MODULE||'@electric-sql/pglite');
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const db=new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role bypassrls;');
await db.exec(readFileSync(new URL('../migrations/029_gta_giveaway.sql',import.meta.url),'utf8'));
const start=Math.floor(Date.now()/1000)*1000-5*3600000;
const ts=m=>new Date(start+m*60000).toISOString();
const q=(s,p=[])=>db.query(s,p);
const val=(s,p=[])=>q(s,p).then(r=>r.rows[0].v);
const observe=(live,s,at,end=null)=>q('select gta_observe($1,$2,$3,$4)',[live,s,at,end]);
const chat=(id,at,name='User'+id)=>val('select gta_record_chat($1,$2,$3) v',[id,name,at]);
const bonus=(s,names)=>val('select gta_award_bonus($1,$2) v',[s,names]);
const board=()=>val('select gta_standings() v');
const rows=()=>board().then(b=>b.entries.map(x=>[x.username,x.xp,x.rank]));
assert.equal((await board()).status,'preview');
await assert.rejects(db.exec("set role anon; select gta_award_bonus(now(),array['a','b','c']);"));
await db.exec('reset role; set role service_role;');
await q('insert into gta_campaign values(1,$1,null)',[ts(0)]);
await observe(true,ts(0),ts(0));
const getCheckpoint=async(m,b)=>(Date.parse(await val('select gta_checkpoint(started_at,checkpoint_seed,$2) v from gta_streams where started_at=$1',[ts(m),b]))-start)/60000;
const first=await getCheckpoint(0,0),second=await getCheckpoint(0,1);
assert.ok(first>=20&&first<30&&second>=50&&second<60);
assert.equal(await bonus(ts(0),['User1','User2','User3']),'stream_not_ended');
assert.equal(await chat(1,ts(1)),true);
assert.equal(await chat(1,ts(1)),true);
for(let m=2;m<first;m+=2)await observe(true,ts(0),ts(m));
assert.equal(await chat(2,ts(first)),true); // boundary message belongs to second window
assert.deepEqual(await rows(),[]);
await observe(true,ts(0),ts(first));
assert.equal(await getCheckpoint(0,0),first);
assert.ok(!('nextCheckIn' in (await board())));
assert.deepEqual(await rows(),[['User1',1,1]]);
assert.equal(await chat(3,ts(first+0.5)),true);
for(let m=first+2;m<second;m+=2)await observe(true,ts(0),ts(m));
await observe(true,ts(0),ts(second));
assert.deepEqual(await rows(),[['User1',1,1],['User2',1,1],['User3',1,1]]);
await observe(false,ts(0),ts(second+2),ts(second+1));
assert.equal(await chat(4,ts(second+1)),false);
assert.equal(await bonus(ts(0),['User1','User2','fake']),'unmatched_handle');
assert.equal(await bonus(ts(0),['User1','USER1','User3']),'duplicate_handle');
assert.equal(await bonus(ts(0),['USER3','user2','User1']),'awarded');
assert.equal(await bonus(ts(0),['User3','User2','User1']),'unchanged');
assert.equal(await bonus(ts(0),['User1','User2','User3']),'already_awarded');
assert.deepEqual(await rows(),[['User3',4,1],['User2',3,2],['User1',2,3]]);
await observe(true,ts(90),ts(90));
const another=await getCheckpoint(90,0);
assert.equal(await chat(1,ts(91)),true);
assert.equal(await chat(3,ts(91)),true);
for(let m=92;m<another;m+=2)await observe(true,ts(90),ts(m));
await observe(true,ts(90),ts(another));
assert.deepEqual(await rows(),[['User3',5,1],['User1',3,2],['User2',3,2]]);
await observe(true,ts(90),ts(another+9)); // known gap after completed checkpoint
assert.deepEqual(await rows(),[['User3',5,1],['User1',3,2],['User2',3,2]]);
assert.equal((await board()).skippedWindows,1);
await q('update gta_campaign set closed_at=$1 where id=1',[ts(another+10)]);
assert.equal(await bonus(ts(0),['User3','User2','User1']),'campaign_closed');
await q('insert into gta_passes values(3)');
assert.deepEqual(await rows(),[['User1',3,1],['User2',3,1]]);
assert.equal((await board()).status,'closed');
console.log('Database integration passed: seeded checkpoints, exact boundary, no calendar leak, duplicate chatter, eligible handle validation, atomic 3/2/1, replay, cross-stream, gap, freeze and pass.');
await db.close();
